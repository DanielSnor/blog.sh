def sitemap_url(loc, lastmod = nil)
  lastmod_tag = lastmod ? "<lastmod>#{lastmod}</lastmod>" : ''
  "<url><loc>#{loc}</loc>#{lastmod_tag}</url>"
end

def render_sitemap(posts, tags_map, content_types)
  urls = [sitemap_url("#{SITE_BASE_URL}/", posts.first && post_time(posts.first).iso8601)]

  posts.each do |post|
    urls << sitemap_url("#{SITE_BASE_URL}#{post_path(post)}", post_time(post).iso8601)
  end

  tags_map.each do |slug, data|
    latest = data[:posts].max_by { |p| p['date'] }
    urls << sitemap_url("#{SITE_BASE_URL}/tag/#{slug}/", latest && post_time(latest).iso8601)
  end

  content_types.each do |type|
    type_posts = posts.select { |post| dominant_content_type(post) == type }
    latest = type_posts.max_by { |p| p['date'] }
    urls << sitemap_url("#{SITE_BASE_URL}/type/#{type}/", latest && post_time(latest).iso8601)
  end

  <<~XML
    <?xml version="1.0" encoding="UTF-8"?>
    <urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
      #{urls.join("\n  ")}
    </urlset>
  XML
end

# Pages are sliced starting from the OLDEST post, so a page's contents never
# change once written. Slicing from the newest end (the obvious way) shifts
# every page boundary each time a post is added, which rewrites the whole
# archive on every new post -- expensive under a content-hash-based deploy.
#
# Numbers therefore run oldest-first: page 1 is the oldest posts, the highest
# number is the newest page and lives at base_path itself (/ or /tag/foo/)
# rather than under /page/. That newest page holds PAGE_SIZE..2*PAGE_SIZE-1
# posts and only splits off a fixed page once it reaches 2*PAGE_SIZE, so the
# landing page is never left nearly empty right after a split.
#
# Returns [[number, posts], ...] newest first, plus the count of fixed
# (already-final) pages.
def anchored_pages(posts)
  fixed = posts.length < 2 * PAGE_SIZE ? 0 : (posts.length / PAGE_SIZE) - 1
  newest_length = posts.length - fixed * PAGE_SIZE
  pages = [[fixed + 1, posts.first(newest_length)]]
  posts.drop(newest_length).each_slice(PAGE_SIZE).with_index do |slice, i|
    pages << [fixed - i, slice]
  end
  [pages, fixed]
end

def page_url(number, fixed, base_path)
  return base_path.empty? ? '/' : "#{base_path}/" if number > fixed

  "#{base_path}/page/#{number}/"
end

# No "x / total" counter: the total changes whenever a new page is created,
# which would put a differing byte on every single page again -- the very
# churn the oldest-anchored slicing above exists to avoid.
def pagination_html(number, fixed, base_path = '')
  return '' if fixed.zero?

  newer = number <= fixed ? %(<a href="#{page_url(number + 1, fixed, base_path)}">#{h(t('pagination.newer'))}</a>) : ''
  older = number > 1 ? %(<a href="#{page_url(number - 1, fixed, base_path)}">#{h(t('pagination.older'))}</a>) : ''
  label = number > fixed ? t('pagination.latest') : t('pagination.page', number: number)
  %(<nav class="pagination">#{newer}<span>#{h(label)}</span>#{older}</nav>)
end

# Templates only contain their own <main>; the header, nav, sidebar and
# footer live once in templates/layout.html.erb and templates/partials/.
# They used to be copy-pasted across all three templates, so every footer
# edit meant three edits that risked drifting apart.
LAYOUT = ERB.new(File.read(File.join(ROOT, 'templates', 'layout.html.erb'), encoding: 'utf-8'))
PARTIALS = {}
PARTIAL_RESULTS = {}

# Cached by name and local variables: partials don't depend on page content
# (nav, sidebar, footer are the same everywhere), so there are only ever a
# few distinct results. Without this cache, every single page would
# re-evaluate several ERB templates, roughly doubling build time on a large
# site.
def partial(name, **locals)
  PARTIAL_RESULTS[[name, locals]] ||= begin
    template = PARTIALS[name] ||=
      ERB.new(File.read(File.join(ROOT, 'templates', 'partials', "#{name}.html.erb"), encoding: 'utf-8'))
    template.result_with_hash(locals)
  end
end

def layout(main_html, title:, description:, path:, image: DEFAULT_OG_IMAGE, og_type: 'website', extra_head: '')
  LAYOUT.result_with_hash(
    main_html: main_html,
    page_title: title,
    page_description: description,
    page_url: "#{SITE_BASE_URL}#{path}",
    og_image: image,
    og_type: og_type,
    extra_head: extra_head
  )
end

# One compiled ERB per template, reused for every page it renders (recompiling
# the same source for every one of what can be thousands of listing pages is
# pure waste).
def write_listing(posts, template, out_root, base_path: '', heading: nil,
                  title: SITE_TITLE, description: SITE_DESCRIPTION)
  pages, fixed = anchored_pages(posts)
  pages.each do |number, page_posts|
    list_html = page_posts.map { |post| render_list_item(post) }.join("\n")
    pagination = pagination_html(number, fixed, base_path)
    out_dir = number > fixed ? out_root : File.join(out_root, 'page', number.to_s)
    # Without this distinction, every listing page would share one identical <title>.
    page_title = number > fixed ? title : "#{title} – #{t('pagination.page', number: number)}"
    main_html = template.result_with_hash(list_html: list_html, pagination: pagination, heading: heading)
    emit(File.join(out_dir, 'index.html'),
         layout(main_html, title: page_title, description: description,
                           path: page_url(number, fixed, base_path)))
  end
  pages.size
end

# public/ isn't wiped and rewritten from scratch. Every output path is
# recorded here, unchanged files are left alone, and whatever the build
# didn't produce this time is removed at the end (prune_public) -- much
# cheaper than deleting everything just to write nearly the same bytes back,
# and avoids re-syncing the whole directory if it lives inside a
# cloud-synced folder.
WRITTEN = {}

def emit(path, content)
  WRITTEN[path] = true
  bytes = content.to_s.b
  return if File.exist?(path) && File.binread(path) == bytes

  FileUtils.mkdir_p(File.dirname(path))
  File.binwrite(path, bytes)
end

# Media is content-addressed by the migration/import step and never edited
# in place, so existence plus size is enough -- hashing every media file on
# every build would cost more than the copy it saves.
def emit_copy(src, dest, compare_content: false)
  WRITTEN[dest] = true
  if File.exist?(dest)
    return if compare_content ? File.binread(dest) == File.binread(src) : File.size(dest) == File.size(src)
  end

  FileUtils.mkdir_p(File.dirname(dest))
  FileUtils.cp(src, dest)
end

# A single pass over public/ -- walking it twice (files separately from
# directories) costs real time once there are thousands of entries, since
# stat-ing each one isn't free, especially on a cloud-synced volume.
def prune_public
  dirs = []
  removed = 0
  Dir.glob(File.join(PUBLIC_DIR, '**', '*'), File::FNM_DOTMATCH).each do |path|
    if File.directory?(path)
      dirs << path
    elsif !WRITTEN[path]
      File.delete(path)
      removed += 1
    end
  end
  # Nothing deleted means no directory could have been orphaned.
  return 0 if removed.zero?

  # Deepest directories first, so emptied trees collapse all the way up.
  dirs.sort_by { |d| -d.length }.each do |dir|
    Dir.rmdir(dir) if Dir.empty?(dir)
  rescue SystemCallError
    nil
  end
  removed
end

