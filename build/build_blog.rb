# The menu a site actually shows. Without a `nav:` key it is what it has
# always been -- All, then one item per content type the site has -- so no
# existing installation renders a byte differently. With one, the site
# names its own items instead:
#
#   nav:
#     - { label: "Home", url: "/" }
#     - { label: "Life in the UK", tag: "life-in-uk" }
#
# `tag:` is a tag's slug and becomes /tag/<slug>/; `url:` is taken as
# written, so an item can point at a post, at a generated page or off the
# site entirely. An entry missing either a label or a destination is
# skipped rather than rendered as an empty link.
#
# An empty list is a decision, not a mistake: the entries and the toggle
# that opens them go away rather than leaving an empty menu behind. That
# is also how a site turns the menu off, so there is no second key for it.
# The <nav> bar itself outlives them, because the search field lives in
# it and templates/layout.html.erb asks for search on every page it
# renders (redirect stubs, which skip layout() on purpose, carry no bar).
# nil means "nothing configured, pick the default menu"; [] means "a menu of
# nothing", and the difference is whether `nav:` is written down at all.
# Until 1.4 a `nav:` key with nothing under it fell back to the default
# menu, while the same emptiness under `links:` meant no links -- one
# editing accident, two opposite answers. A key that is written down now
# speaks for itself everywhere.
def configured_nav_items
  return nil unless SiteConfig.key?('nav')

  entries = SiteConfig.get('nav', default: nil)
  # Written down but not a list: doctor names it, and the build takes the
  # key at its word rather than quietly restoring a menu nobody asked for.
  return [] unless entries.is_a?(Array)

  entries.filter_map do |entry|
    next unless entry.is_a?(Hash)

    label = entry['label'].to_s.strip
    slug = entry['tag'].to_s.strip
    href = slug.empty? ? entry['url'].to_s.strip : "/tag/#{slug}/"
    next if label.empty? || href.empty?

    [href, label]
  end
end

