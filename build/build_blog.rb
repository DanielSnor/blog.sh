# A media file's own name, ready to be put in an attribute. Two things go
# wrong without this, and both arrive through an ordinary import of
# somebody else's archive rather than through anything the author typed.
#
# The name is attacker-controlled: Import::Media#allocate numbers the file
# but keeps File.extname verbatim, and an extension is only "everything
# after the last dot" -- quotes and angle brackets included. Unescaped in
# src="..." that closes the attribute and opens a tag, which is stored XSS
# on the author's own domain. (The alt attribute one line over has been
# escaped all along; this is the asymmetry, not a new requirement.)
#
# And a name is not a path: "../" in it walks out of the post's directory,
# both when the page links it and when the build copies it. The name is
# taken as a basename, so a crafted one lands beside the post or nowhere.
# A media file's own name, ready to be put in an attribute -- and to be
# read back as a path by a browser, which is where this used to stop.
#
# h() escapes the markup, so a name could not break out of the attribute;
# nothing escaped the URL, so a name could break out of the PATH. A picture
# called "foto #1.jpg" produced src="…/foto #1.jpg", where a browser reads
# "…/foto " and takes "#1.jpg" as a fragment: no request, no picture, no
# error anywhere. A "%" did the same by starting an escape sequence of its
# own, and a "?" by starting a query.
#
# Only the characters that actually change how a path is read are encoded.
# Letters with diacritics are left alone deliberately: browsers handle them,
# every existing site already has them in its markup, and encoding them
# would rewrite pages that have nothing wrong with them.
URL_UNSAFE_IN_PATH = /[#%?"'<>\s\\^`{|}]/.freeze

# The address half, with no markup escaping: og:image and the JSON-LD go
# through their own (a template h(), and to_json), and a second layer
# there would put a literal &amp; in a URL.
def media_name_encoded(name)
  File.basename(name.to_s).gsub(URL_UNSAFE_IN_PATH) { |c| format('%%%02X', c.ord) }
end

def media_src(prefix, name)
  "#{prefix}#{h(media_name_encoded(name))}"
end

# Characters XML 1.0 forbids ANYWHERE in a document -- CDATA included, which
# is the part that caught this out. lib/import/xml_repair.rb strips them from
# an export on the way in but leaves CDATA regions byte for byte on purpose,
# and a WordPress post body IS inside CDATA, so one control character in an
# old export landed in the post JSON and went straight into
# <description><![CDATA[...]]></description>. libxml2 -- which is what most
# feed readers are -- then refuses the WHOLE document, so one character in
# one post takes every subscriber's feed away, and neither the build nor
# check says a word. Tab, newline and carriage return are the three allowed.
XML_FORBIDDEN = /[\x00-\x08\x0B\x0C\x0E-\x1F]/

def xml_text(text)
  text.to_s.gsub(XML_FORBIDDEN, '')
end

# "]]>" cannot appear inside a CDATA section at all -- the only escape is
# to end the section and start another around the ">".
def cdata_safe(text)
  xml_text(text).gsub(']]>', ']]]]><![CDATA[>')
end


# Where this post's media actually are: under the file's year, and -- for an
# archive written before that was settled -- under the date's year if the
# first has nothing.
def media_source_dir(post, date_year)
  by_file = File.join(MEDIA_DIR, (post['__year'] || date_year).to_s, post['slug'].to_s)
  return by_file if Dir.exist?(by_file)

  by_date = File.join(MEDIA_DIR, date_year.to_s, post['slug'].to_s)
  Dir.exist?(by_date) ? by_date : by_file
end

def referenced_media_filenames(post)
  post['content'].flat_map do |block|
    [(block['media'] || []).first, (block['poster'] || []).first].compact.map { |m| m['url'] }
  end.compact
end

# What a post's own page is built from, beyond the post file itself.
#
# Three things reach into a post page from outside it, and all three change
# without the post changing:
#
#   the series -- "part 3 of 7" and the links either side are facts about
#     the set, so a sibling joining or leaving rewrites this post's page;
#     so does somebody spelling the series name differently.
#   its tags -- a tag pill is a link when the tag has a listing page and a
#     flat pill when it does not, and whether it has one depends on the
#     OTHER posts carrying it.
#   its media -- a picture replaced in place changes the page's width and
#     height attributes without changing a byte of the post.
#
# Anything else that could reach in is in the fingerprint already. The
# media stat is the only cost here, and the loop below stats those same
# files anyway.
def post_page_key(post, source_media_dir)
  slug, in_series, = series_context(post)
  # Everything this page says about its siblings is made out of the
  # siblings: the name and "part 3 of 7" at the top, and at the bottom
  # prev/next carrying each neighbour's ADDRESS and TITLE. The key used to
  # carry their slugs, which is neither -- so a sibling retitled left stale
  # words on every other member's page, and a sibling whose date was
  # corrected across a year left every neighbour linking at a 404, both
  # without touching the pages that were now wrong.
  #
  # Their digests rather than their titles and addresses on purpose: what
  # the nav shows about a neighbour has grown before and will again, and a
  # key listing today's fields goes blind the day one is added. A series is
  # a handful of posts, so the cost of rebuilding all of them when one
  # changes is a handful of pages.
  series_bit = if slug
                 "#{slug}/#{SERIES_NAMES[slug]}:" +
                   in_series.map { |p| "#{post_path(p)}=#{POST_DIGEST[p['__path']]}" }.join(',')
               elsif draft?(post) && !post['series'].to_s.strip.empty?
                 # A draft is not in SERIES_MAP -- "part 3 of 7" is a fact
                 # about the published set and the draft is not in it -- so
                 # the branch above never covered it and nothing else did
                 # either. Its note is built entirely out of things that
                 # move without the draft being touched: how many of the
                 # series are published, and how the published ones spell
                 # its name.
                 #
                 # Their digests and not merely how many there are, for the
                 # reason the branch above lists its siblings' digests: the
                 # position the draft is previewed at is worked out from the
                 # published parts' dates and part numbers, so correcting a
                 # sibling's date moves the draft's number without changing
                 # the count, and the cached preview would have kept the old
                 # one.
                 draft_slug = series_slug_of(post)
                 ['draft', post['series'], draft_slug, SERIES_NAMES[draft_slug],
                  Array(SERIES_PUBLISHED[draft_slug]).map { |p| POST_DIGEST[p['__path']] }.join(',')].join('/')
               else
                 ''
               end
  tag_bit = Array(post['tags']).map { |tag| "#{tag_slug(tag)}=#{TAG_PAGES[tag_slug(tag)] ? 1 : 0}" }.join(',')
  media_bit = referenced_media_filenames(post).map do |name|
    file = File.join(source_media_dir, File.basename(name.to_s))
    stat = begin
      File.stat(file)
    rescue SystemCallError
      nil
    end
    "#{File.basename(name.to_s)}:#{stat ? "#{stat.size}:#{stat.mtime.to_i}" : '-'}"
  end.join(',')
  Digest::SHA256.hexdigest([POST_DIGEST[post['__path']], series_bit, tag_bit, media_bit].join('|'))
end

(posts + pages + unlisted_posts + drafts).each do |post|
  year = post_time(post).year
  dir = output_dir(post)

  # Media stays in media/<year>/<slug>/ even for drafts -- publishing
  # doesn't move files, it just moves the output page. The year here is the
  # one the FILE lives under, not the one its date says: those two part
  # company when a date is corrected across a year boundary, and every
  # other part of the engine (check, export, delete, restore, the editor)
  # reads the file's own year.
  source_media_dir = media_source_dir(post, year)
  referenced_media_filenames(post).each do |name|
    # Basename for the same reason the page uses one: a "filename" carrying
    # "../" is a path, and File.join would honour it -- on the way in it
    # reads a file the post has no business reading, and on the way out it
    # writes outside public.nosync/, where prune can never clean it up.
    filename = File.basename(name.to_s)
    next if filename.empty? || filename == '.' || filename == '..'

    src = File.join(source_media_dir, filename)
    dest = File.join(dir, filename)
    if File.exist?(src)
      emit_copy(src, dest)
    else
      warn t('build.media_missing', slug: post['slug'], filename: filename)
      # The page still links this file, so a copy already in public.nosync
      # has to survive prune_public -- otherwise a source that is missing
      # for a moment (a media directory mid-move, a file being replaced)
      # makes the build delete the last copy, and the --prune that every
      # publish runs then deletes it from the live site as well.
      WRITTEN[dest] = true if File.exist?(dest)
    end
  end

  dest = File.join(dir, 'index.html')
  key = post_page_key(post, source_media_dir)
  if BuildCache.page_fresh?(dest, key)
    # Not rendered, not compared, not written -- the file on disk was built
    # from these exact inputs by this exact engine and is still untouched.
    # This is what makes publishing cost the size of the CHANGE rather than
    # the size of the archive.
    keep(dest)
  else
    emit(dest, render_post_html(post, post_template))
    BuildCache.remember_page(dest, key)
  end
end

# A tiny self-contained page, deliberately not layout(): a reader spends a
# fraction of a second here, and a stub carrying the full nav, CSS and
# widgets would be a second copy of the site chrome to keep in sync for a
# page whose entire job is to leave. noindex keeps it out of search
# results in favour of the canonical target.
def redirect_stub_html(post)
  url = "#{SITE_BASE_URL}#{post_path(post)}"
  <<~HTML
    <!doctype html>
    <html lang="#{SITE_LANG}">
    <head>
    <meta charset="utf-8">
    <meta http-equiv="refresh" content="0; url=#{url}">
    <link rel="canonical" href="#{url}">
    <meta name="robots" content="noindex">
    <title>#{h(post_title_for(post))}</title>
    </head>
    <body>
    <p>#{h(t('redirect.moved'))} <a href="#{url}">#{h(url)}</a></p>
    </body>
    </html>
  HTML
end

# A renamed post keeps answering at every address it ever had: each entry
# in former_slugs ("year/slug", frozen at rename time) becomes a one-page
# stub redirecting to the post's current URL. Emitted after the real
# pages so a stub can never overwrite one -- if a NEW post has since
# taken an old address, the live page wins and the skip is said out loud,
# because a silent stub there would hijack it. Drafts emit nothing: an
# unpublished post is off the site, old addresses included, and the stubs
# come back when it does. Stubs stay out of listings, feeds, the sitemap
# and the search index by construction -- they are not posts.
#
# Pages are in here as well as posts: a renamed page owes its old
# address exactly what a renamed post does. They are out of the
# LISTINGS, not out of the engine's promises.
# Whether this volume treats two names differing only in case or in unicode
# form as one file. macOS APFS does both by default, and that is where this
# matters: the stub loops below guard against clobbering the build's own
# output with a byte-exact WRITTEN lookup, so `public/About/index.html` and
# `public/about/index.html` -- one file on such a volume -- slipped past it.
# emit then wrote the redirect stub straight over the page the build had
# produced seconds earlier: the page's content gone, and the address serving
# a meta-refresh to itself, which is an infinite loop for every visitor.
#
# Probed once rather than assumed, because the answer decides whether the
# folded index below is consulted at all -- on a case-sensitive volume
# /About/ and /about/ are two real addresses and refusing one would be
# wrong.
def case_folding_public?
  return @case_folding_public unless @case_folding_public.nil?

  FileUtils.mkdir_p(PUBLIC_DIR)
  probe = File.join(PUBLIC_DIR, '.blogsh-case-probe')
  File.binwrite(probe, '')
  @case_folding_public = File.exist?(File.join(PUBLIC_DIR, '.BLOGSH-CASE-PROBE'))
  File.delete(probe)
  @case_folding_public
rescue StandardError
  @case_folding_public = false
end

def fold_path(path)
  path.to_s.unicode_normalize(:nfc).downcase
end

# The same question WRITTEN answers, asked the way the volume will answer it.
def written_already?(dest)
  return true if WRITTEN[dest]
  return false unless case_folding_public?

  @written_folded ||= {}
  if @written_folded.size != WRITTEN.size
    @written_folded = WRITTEN.keys.to_h { |k| [fold_path(k), true] }
  end
  @written_folded.key?(fold_path(dest))
end

# The longest a single path segment may be. POSIX NAME_MAX is 255 bytes on
# macOS and Linux alike, and mkdir_p raises ENAMETOOLONG past it -- which
# killed the build at its very LAST stage, after the whole site had already
# been written, with a backtrace naming no post. An imported permalink is
# where such a segment comes from: 36 Japanese characters percent-encode to
# 333 bytes, and importers put the source URL's path straight into
# redirect_from. The three collisions below are already guarded on the
# stated grounds that one bad imported entry must not kill the build; a
# name the filesystem refuses is the fourth.
NAME_MAX_BYTES = 255

(posts + pages + unlisted_posts).each do |post|
  Array(post['former_slugs']).each do |former|
    parts = former.to_s.split('/').reject(&:empty?)
    # "." and ".." can only arrive via a hand-edited JSON (slugify never
    # emits them), but hand-edited JSON is exactly where this list lives
    # -- and a ".." here would write the stub outside posts/, up to and
    # including over the homepage or above public.nosync entirely.
    unless parts.size == 2 && parts.none? { |p| p == '.' || p == '..' } &&
           parts.none? { |p| p.bytesize > NAME_MAX_BYTES }
      warn t('build.former_slug_unusable', slug: post['slug'], entry: former.inspect)
      next
    end

    dest = File.join(PUBLIC_DIR, 'posts', *parts, 'index.html')
    if written_already?(dest)
      warn t('build.former_slug_taken', slug: post['slug'], former: former)
      next
    end

    emit(dest, redirect_stub_html(post))
  end
end

