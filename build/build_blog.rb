        %(data-share-url="#{h(share_url)}" data-share-done="#{h(t('share.copied'))}" ) +
        %(data-share-failed="#{h(t('share.copy_failed'))}" ) +
        %(title="#{h(t('share.copy'))}" aria-label="#{h(t('share.copy'))}">#{SHARE_ICONS['copy']}</button>)
