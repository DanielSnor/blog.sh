def render_list_item(post, pinned: false)
  # The pinned copy is rendered separately and NOT cached under the same
  # key: it differs from the post's ordinary appearance by exactly the
  # badge mark, and caching one over the other would leak the mark into
  # the chronological copy (or lose it from the pinned one).
  return build_list_item(post, pinned: true) if pinned

  LIST_ITEM_CACHE[post] ||= build_list_item(post)
end

def build_list_item(post, pinned: false)
  prefix = post_path(post)
  # A post that wrote its own teaser shows exactly that here, and nothing
  # below it: the listing is where the site invites, and an author who wrote
  # the invitation should not have it padded with the first 500px of the
  # article. The CSS clip is dropped with it -- there is nothing left to
  # clip, and a fade over a finished sentence reads as damage. "Read more"
  # stays, because the post does continue.
  #
  # An empty teaser is honoured in the toot but not here: a card with a
  # heading and no words looks like a build that went wrong, and nobody
  # asking for a quiet announcement is asking for that.
  teaser = PostText.teaser_blocks(post['content'])
  teaser = nil unless teaser&.any?
  # `lifted:` on this branch too. A post's own page passes it so the link
  # block renders WITHOUT the title the heading borrowed from it; the
  # teaser branch did not, so a card printed the borrowed headline twice
  # -- once as its <h2> and again in the body under it -- while the post's
  # own page printed it once.
  content = if teaser
              render_content(teaser, prefix, lifted: link_title_block(post))
            else
              post_content_html(post)
            end
  # Heading anchors belong to the post's own page. A listing stacks ten
  # posts' bodies into ONE document, so two posts that both have a
  # "Co dal?" section put id="co-dal" on the page twice -- 105 pages of a
  # real archive carried duplicate ids, which makes the document invalid
  # and sends any same-page anchor to whichever came first. heading_id
  # de-duplicates within a post; nothing could de-duplicate across them,
  # because each post's HTML is rendered (and cached) on its own.
  content = content.gsub(%r{<(h[1-6])([^>]*) id="[^"]*"}) { "<#{Regexp.last_match(1)}#{Regexp.last_match(2)}" }
  excerpt = teaser ? false : excerpt?(post)
  content_class = excerpt ? 'content excerpt' : 'content'
  more = teaser || excerpt
  read_more = more ? %(<a class="read-more" href="#{prefix}">#{h(t('post.read_more'))}</a>) : ''
  title = post_heading_html(post, 'h2', prefix)
  stats = post_meta_html(post, reading_labels(post))
  <<~HTML
    <div class="card post-list-item">
      <div class="post-header">
        #{date_badge(post, link: prefix, pinned: pinned)}
        <div class="post-body">
          #{title}
          #{stats}
          <div class="#{content_class}">
            #{content}
          </div>
          #{read_more}
          #{tags_html(post)}
        </div>
      </div>
    </div>
  HTML
end

# Every post is automatically tooted to Mastodon, where the link shows a
# preview -- without og:image that would be bare text. Uses the post's first
# non-degenerate image; text posts fall back to the site banner.
def post_og_image(post)
  block = post['content'].find { |b| b['type'] == 'image' && !degenerate_image?(b) }
  media = block && (block['media'] || []).first
  return DEFAULT_OG_IMAGE unless media && media['url']

  # Basename, the same as the page's own <img> uses: this address goes into
  # og:image and into the JSON-LD, and a name carrying "../" pointed both
  # of them outside the post -- at whatever happens to sit there.
  # Percent-encoded, like the page's own <img>. 83baf51 escaped the URL
  # in the markup and left these two behind, so the picture on the page
  # pointed at foto%20%231.jpg while og:image pointed at "foto #1.jpg" --
  # where a scraper reads everything from the # as a fragment, requests
  # "foto " and gets a 404. The link card on Mastodon and Bluesky and the
  # search engine's thumbnail were then blank for exactly the pictures
  # whose names needed the encoding most.
  "#{SITE_BASE_URL}#{post_path(post)}#{media_name_encoded(media['url'])}"
end

def post_description(post)
  # A teaser the author wrote is what the post says about itself, so it wins
  # over the cut here too. The empty teaser is the one place this parts ways
  # with the toot: there, "marker on the first line" means "announce with the
  # title and link alone" and an empty perex honours it. A description is not
  # a message but standing metadata -- it is what a search engine quotes
  # months later -- so an empty one would cost the post something without
  # anybody having asked for that, and the cut stands in.
  # A link card shows the title above the description, so when the title was
  # taken from the post's own opening the description has to carry on from
  # there. Otherwise the card reads the same sentence twice -- which did not
  # happen while the title was a slug, and would have arrived with this
  # release as a new defect rather than a fix.
  # ...but only while there IS something after the name. A post short enough
  # to be named in full leaves nothing behind it, and taking that emptiness
  # at face value cost 286 posts on one real archive their own description
  # and gave them the site's instead -- a card that stopped saying what the
  # post is and started saying what the site is. Repeating the text under
  # the title is the lesser of the two: it still describes this post.
  name, rest = PostText.name_and_rest(post)
  text = if name && !rest.to_s.strip.empty?
           rest
         else
           teaser = PostText.teaser_blocks(post['content'])
           teaser&.any? ? PostText.plain('content' => teaser) : plain_text_for_search(post)
         end
  text = post['title'].to_s if text.to_s.strip.empty?
  text = SITE_DESCRIPTION if text.strip.empty?
  truncate_excerpt(text, META_DESCRIPTION_LENGTH)
end

# What a crawler is told about a post beyond the OG basics: the article's
# time and tags as og meta, and the same facts once more as schema.org
# JSON-LD, which is what rich results actually read. Only for published
# posts -- a draft's date is bookkeeping and the page is noindex anyway.
#
# The JSON-LD block is data, not script: CSP's script-src governs
# execution, and a text/ld+json block never executes, so the strict
# policy above needs no widening. "</" is escaped so post text can never
# close the script element from inside the JSON.
def post_structured_head(post)
  published = post_display_time(post).iso8601
  tags = post['tags'] || []
  lines = [%(<meta property="article:published_time" content="#{h(published)}">)]
  lines += tags.map { |tag| %(<meta property="article:tag" content="#{h(tag)}">) }

  data = {
    '@context' => 'https://schema.org',
    '@type' => 'BlogPosting',
    'headline' => post_title_for(post),
    'datePublished' => published,
    'url' => "#{SITE_BASE_URL}#{post_path(post)}",
    'mainEntityOfPage' => "#{SITE_BASE_URL}#{post_path(post)}",
    'author' => { '@type' => 'Person', 'name' => SITE_AUTHOR },
    'image' => post_og_image(post),
    'description' => post_description(post)
  }
  data['keywords'] = tags.join(', ') unless tags.empty?
  # Both sequences that can end a script block from inside a JSON string:
  # "</" closes it, and "<!--" opens an HTML comment whose scope runs to the
  # next "-->" -- so a post whose text held an unterminated comment followed
  # by another "<script" swallowed the rest of the page and rendered blank.
  # Escaping the "<" is invisible once the JSON is parsed and stops both.
  json_ld = JSON.generate(data).gsub('</', '<\/').gsub('<!--', '<\u0021--')
  lines << %(<script type="application/ld+json">#{json_ld}</script>)
  lines.map { |line| "\n  #{line}" }.join
end

# The post's lead image, when the site shows one: the first image whose
# size is known and sane, together with the media entry the markup needs.
# A post's own `hero:` overrides the site's answer in both directions --
# the same two doors `pinned` has, and it reads the same spellings, so a
# post that wants to keep its photo in the text says `hero: false` and one
# on a site without heroes can still ask for one.
#
# Degenerate images are skipped rather than lifted: a 1x1 tracking pixel
# from some imported archive would otherwise become the page's lead
# picture. A post with nothing suitable simply keeps the ordinary layout,
# so there is no second template to keep in step with this one.
# The date in the hero's byline, or nothing at all on a page.
#
# The rule is the same one the date badge follows -- "Contact, 1 July 2022"
# says nothing except that somebody had to type a date into a field -- but
# it was written into only one of the two places a date reaches the top of
# the page. A page with no usable image looked right, so the hole stayed
# shut until Ivan's About page turned out to have a portrait.
#
# A helper returning '' rather than a conditional in the template, for the
# reason reading_time_html gives: post.html.erb renders for every post on
# the site, and a block tag on its own line leaves its newlines on all of
# them.
# The same question the badge answers, in the layout that has no badge: with
# a hero the date lives in the byline under the picture, so on a titled post
# it is a <time> and on an untitled one it is the heading -- a <time> inside
# an h1, which keeps the machine-readable date and gives the page the
# outline entry it had none of. See date_badge for why the date rather than
# a clipped copy of it.
def hero_time_html(post, heading: false)
  return '' if page?(post)

  stamp = %(<time datetime="#{h(post_time(post).iso8601)}">#{h(post_display_date(post))}</time>)
  link = archive_link_for(post)
  stamp = %(<a href="#{h(link)}">#{stamp}</a>) if link
  heading ? %(<h1 class="post-hero__date">#{stamp}</h1>) : stamp
end

# Where a post's own date stamp leads: to the month it was written in,
# inside the archive index. The stamp is on every post page and led nowhere
# until now, so the index is reachable from anywhere in the archive without
# adding a control to the page.
#
# Nil for anything the index does not list -- a draft, a page, an unlisted
# post -- because a stamp pointing at a year page that will not mention it
# is worse than a stamp pointing nowhere.
#
# The year is the ADDRESS's, matching what the index groups by and what the
# checker will look for.
def archive_link_for(post)
  return nil if draft?(post) || page?(post) || unlisted?(post)

  time = post_time(post)
  "/archive/#{time.year}/#m#{format('%02d', time.month)}"
end

# Whether the post says what it is called. Untitled posts -- an imported
# tweet, a photograph with a caption -- borrow a title from a link block if
# they carry one, and otherwise have none at all; on those the date does the
# job, and this is what asks.
def post_names_itself?(post)
  !post['title'].nil? || !link_title_block(post).nil?
end

def hero_for(post)
  return nil unless post.is_a?(Hash)

  setting = post['hero']
  wanted = setting.nil? ? LAYOUT_HERO : !%w[false no 0].include?(setting.to_s.strip.downcase)
  return nil unless wanted

  block = (post['content'] || []).find do |b|
    b.is_a?(Hash) && b['type'] == 'image' && !degenerate_image?(b)
  end
  return nil unless block

  media = (block['media'] || []).first
  media && media['url'] ? [block, media] : nil
end

# Empty string rather than a conditional in the template: post.html.erb
# renders for every post on the site, and a block tag on its own line
# leaves its newlines on all of them whether or not the block runs -- so a
# post with none of these has to come out exactly as it did before.
# The clock sits in the same row as the favourites, boosts and replies,
# because it is the same kind of fact: something to know about the post
# before deciding to read it. On its own line above the text it read as an
# announcement.
#
# The row is a block of its own, and that is not tidiness: the contents
# list floats, and a float takes the top of the line box it lands in. With
# the counts and the clock as loose inline boxes, that line WAS the
# metadata -- so the contents began level with the star rather than level
# with the article. Wrapped, the float starts after the row, which is
# where the text starts too.
#
# The number is bare ("6 min") since the icon already says what it counts;
# the full sentence stays as the accessible name, which is where a screen
# reader needs it and where an icon says nothing at all.
# 16px and a radius of 9, to match the star, the boost and the comment
# bubble it stands in a row with (assets/js/comments.js). It was 18 with a
# radius of 9.5, and the two compounded: a bigger box AND a shape filling
# more of it, so the clock read about a fifth larger than its neighbours.
# The other three are centred by the flex row; this one is `display: inline`
# for the hero byline's baseline (see .post-stat.reading-time), so its
# vertical-align carries the size change with it.
READING_TIME_ICON = '<svg viewBox="0 0 24 24" width="16" height="16" fill="none" ' \
                    'stroke="currentColor" stroke-width="2" stroke-linecap="round" ' \
                    'stroke-linejoin="round" aria-hidden="true">' \
                    '<circle cx="12" cy="12" r="9"/><path d="M12 7V12l3.5 2"/></svg>'

# What a post's reading time SAYS, short one included. Kept apart from the
# markup because two callers need the same words and one of them (the hero
# byline) draws them somewhere else entirely.
#
# A post under the length at which the engine stops calling it a photo with
# a caption has no minutes to report, and used to report nothing at all.
# It says "under a minute" now, and that is a layout decision more than an
# informational one: on an archive like sean.cz, eleven posts out of 4,394
# carry an announcement, so from the second page of the archive onwards NO
# card had a meta row -- and the few that did stood out as a break in the
# rhythm rather than as a card with more to say. With this every card
# carries exactly one row. See docs/decisions.md.
def reading_labels(post)
  minutes = reading_minutes(post)
  return [t('post.reading_time_under'), t('post.reading_minutes_under')] unless minutes

  [t('post.reading_time', minutes: minutes), t('post.reading_minutes', minutes: minutes)]
end

# nil means "not here" -- the one caller that passes it is the post page
# with a lead image, where the byline under the picture carries the reading
# time and a second copy above the text would be the same fact twice. It no
# longer doubles as "this post is too short to time": that case has words of
# its own now, and conflating the two is what would have printed the reading
# time in both places on a short post with a hero.
def reading_time_html(labels)
  return '' unless labels

  title, short = labels
  %(<span class="post-stat reading-time" title="#{h(title)}" ) +
    %(aria-label="#{h(title)}">#{READING_TIME_ICON}) +
    %(<span>#{h(short)}</span></span>)
end

# '' when there is nothing to put in it: a site with no comments network and
# a post whose reading time is drawn elsewhere has to come out exactly as it
# did before this row existed.
def post_meta_html(post, labels)
  stats = post_stats_html(post)
  reading = reading_time_html(labels)
  return '' if stats.empty? && reading.empty?

  %(<div class="post-meta">#{stats}#{reading}</div>)
end

def toc_html(entries)
  return '' if entries.empty?

  items = entries.map do |e|
    %(<li class="toc-l#{e['level']}"><a href="##{h(e['id'])}">#{h(e['text'])}</a></li>)
  end.join
  %(<nav class="toc" aria-label="#{h(t('post.toc_label'))}"><p class="toc-heading">#{h(t('post.toc_heading'))}</p><ol>#{items}</ol></nav>\n                )
end

# Where a post sits in its series, and the way on. Only ever within the
# series: chronological neighbours across a whole archive are usually
# unrelated -- on an archive assembled from twenty-two sources, "next" is
# a tweet from 2011 beside an essay from 2026, which is noise wearing the
# clothes of navigation.
def series_nav_html(slug, in_series, index, position, post = nil)
  # A draft is not in SERIES_MAP -- "part 3 of 7" is a fact about the
  # published set and the draft is not in it. But saying NOTHING made a
  # typo in the series name invisible until the address was live and the
  # toot sent: a misspelling quietly founds a one-post series, and with
  # fewer than two members it does not even get a page to notice it on.
  # So a draft's preview answers the question that actually matters while
  # previewing -- does this join something, or start something new?
  if post && draft?(post) && position == :top
    name = post['series'].to_s.strip
    return '' if name.empty?

    draft_slug = series_slug_of(post)
    published = defined?(SERIES_PUBLISHED) ? (SERIES_PUBLISHED[draft_slug] || 0) : 0
    label = if published.positive?
              spelled = (defined?(SERIES_NAMES) && SERIES_NAMES[draft_slug]) || name
              t('post.series_draft_joins', name: spelled, count: published, number: published + 1)
            else
              t('post.series_draft_new', name: name)
            end
    return %(<p class="series-note series-note--draft">#{h(label)}</p>\n                )
  end

  return '' if slug.nil? || in_series.size < 2

  if position == :top
    label = t('post.series_part', name: h(SERIES_NAMES[slug].to_s), number: index + 1, total: in_series.size)
    return %(<p class="series-note"><a href="/series/#{h(slug)}/">#{label}</a></p>\n                )
  end

  prev_post = index.positive? ? in_series[index - 1] : nil
  next_post = in_series[index + 1]
  return '' if prev_post.nil? && next_post.nil?

  links = []
  links << %(<a class="series-prev" href="#{h(post_path(prev_post))}">#{h(t('post.series_previous', title: post_title_for(prev_post)))}</a>) if prev_post
  links << %(<a class="series-next" href="#{h(post_path(next_post))}">#{h(t('post.series_next', title: post_title_for(next_post)))}</a>) if next_post
  # Named, like the table of contents is. A screen reader lists the
  # landmarks on a page, and a post can carry three <nav>s -- the site
  # bar, this one and the pagination -- of which only the toc had a name.
  # Three entries reading "navigation" are three guesses.
  %(<nav class="series-nav" aria-label="#{h(t('post.series_nav_label'))}">#{links.join}</nav>\n                )
end

# A link post carries no title of its own -- what the reader takes for its
# title lives inside its link block. The engine therefore had nothing to put
# in a heading, in <title>, or in a feed item: listings and post pages
# printed no heading at all and the title came out as bold body text inside
# the article, while the tab and the feed printed the slug.
#
# The first link block that has a title lends it to the post. The block then
# renders without it (see render_block), or the page would say it twice.
def link_title_block(post)
  PostText.link_title_block(post)
end

def post_title_for(post)
  return post['title'].to_s if post['title']

  block = link_title_block(post)
  return block['title'].to_s if block

  # The slug used to stand in here, which meant the same post was called two
  # different things: a date in its own heading and
  # "burtiky-opekame-hipstamatic-oggl-jane" in the browser tab, the link card
  # and the feed. A slug is an address, made by machine out of the words --
  # so the words themselves are the better name, and the post's own heading
  # stays the date it has been since 1.3.
  name, = PostText.name_and_rest(post)
  name || post['slug'].to_s
end

# The heading itself. A post's own title links to the post in a listing and
# is plain text on the post's own page -- `self_href` nil says which. A link
# post's borrowed title goes where the link goes in both places: on a blog
# of links that is the thing the reader is reaching for, and the date badge
# beside it is still the way to the post's own page.
def post_heading_html(post, level, self_href)
  if post['title']
    inner = self_href ? %(<a href="#{self_href}">#{h(post['title'])}</a>) : h(post['title'])
    return %(<#{level}>#{inner}</#{level}>)
  end

  block = link_title_block(post)
  return '' unless block

  %(<#{level}><a href="#{h(block['url'])}">#{h(block['title'])}</a></#{level}>)
end

def render_post_html(post, template)
  toc = toc_for(post)
  series_slug, series_posts, series_index = series_context(post)
  hero_block, hero_media = hero_for(post)
  # Rendered without the lifted block, or the same photo appears twice --
  # once as the lead and once where it was written. Only the hero path
  # pays for the extra render; every other post keeps the memoized one.
  # `lifted:` here too -- without it a link post with a hero printed the
  # borrowed title twice, once as the h1 and again in full inside the
  # link card.
  #
  # And the hero is dropped by IDENTITY, not by value: Array#- compares
  # with ==, so a post showing the same photograph twice (same media, same
  # caption) lost BOTH copies when hero_for lifted the first one.
  content_html = if hero_block
                   rest = post['content'].reject { |b| b.equal?(hero_block) }
                   render_content(rest, post_path(post), lifted: link_title_block(post))
                 else
                   post_content_html(post)
                 end
  draft_banner = draft?(post) ? draft_banner(post) : ''
  layout(template.result(binding),
         title: draft?(post) ? "#{t('post.draft_title_prefix')}#{post_title_for(post)}" : post_title_for(post),
         description: post_description(post),
         path: post_path(post),
         image: post_og_image(post),
         og_type: 'article',
         # Drafts and unlisted posts must never end up in search engines
         # or link previews -- for an unlisted post that is the whole
         # point, since being out of the sitemap only stops the crawler
         # being told, not the crawler arriving from a link.
         extra_head: if draft?(post) || unlisted?(post)
                       %(\n  <meta name="robots" content="noindex, nofollow">)
                     else
                       post_structured_head(post)
                     end,
         frame_origins: Embed.frame_origins_for(post['content']),
         comment_origins: comment_origins_for([post]))
end

def rss_item(post)
  url = "#{SITE_BASE_URL}#{post_path(post)}"
  title = CGI.escapeHTML(post_title_for(post))
  pub_date = post_time(post).rfc2822
  description = render_content(post['content'], "#{SITE_BASE_URL}#{post_path(post)}")
  # A post's rendered HTML goes into the feed inside CDATA, and CDATA has
  # exactly one way to end. A post carrying "]]>" -- which an imported
  # embed_html can, since it is stored verbatim -- closed the section
  # early and the rest of it was read as feed markup: a reader could be
  # handed a <title> and <link> of the post's choosing, in an item that
  # still validated. The sequence is split across two CDATA sections, the
  # standard way, so it survives as text.
  # The same visibility rule the pills follow (a tag that slugs to nothing
  # is dropped), and the same coercion every other escape in this file
  # uses -- a non-string tag out of a hand-edited JSON used to end the
  # whole build in CGI.escapeHTML.
  categories = (post['tags'] || []).reject { |t| tag_slug(t).empty? }
                                   .map { |t| "<category>#{h(t)}</category>" }.join
  <<~ITEM
    <item>
      <title>#{xml_text(title)}</title>
      <link>#{url}</link>
      <guid isPermaLink="true">#{url}</guid>
      <pubDate>#{pub_date}</pubDate>
      <description><![CDATA[#{cdata_safe(description)}]]></description>
      #{categories}
    </item>
  ITEM
end

def render_rss(posts, path: '/rss.xml', title: SITE_TITLE, description: SITE_DESCRIPTION,
               link: "#{SITE_BASE_URL}/")
  items = posts.first(RSS_ITEM_LIMIT).map { |post| rss_item(post) }.join
  # The newest post's date, not Time.now -- otherwise rss.xml differs on
  # every build and gets re-uploaded even when nothing changed.
  # RSS 2.0 wants an RFC-822 date-time here, and an empty element is not
  # one: a site with nothing in the stream yet published
  # <lastBuildDate></lastBuildDate>, which strict readers refuse along with
  # the whole feed. The build's own clock is the honest answer to "when was
  # this feed last built" when no post can answer it.
  last_build = (posts.first ? post_time(posts.first) : Time.now).rfc2822
  <<~XML
    <?xml version="1.0" encoding="UTF-8"?>
    <rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">
      <channel>
        <title>#{h(xml_text(title))}</title>
        <link>#{link}</link>
        <atom:link href="#{SITE_BASE_URL}#{path}" rel="self" type="application/rss+xml" />
        <description>#{h(xml_text(description))}</description>
        <language>#{SITE_LANG}</language>
        <lastBuildDate>#{last_build}</lastBuildDate>
        #{items}
      </channel>
    </rss>
  XML
end

def sitemap_url(loc, lastmod = nil)
  lastmod_tag = lastmod ? "<lastmod>#{lastmod}</lastmod>" : ''
  "<url><loc>#{loc}</loc>#{lastmod_tag}</url>"
end

# `entries`, not `posts`: the caller hands this posts AND pages, and the name
# it used to have is what produced the defect below. Everything with an
# address belongs on a sitemap, so the combined list is right for the URL
# list -- but the archive is built from the STREAM alone, so it is given the
# stream rather than left to guess from a list that is not one.
def render_sitemap(entries, tags_map, content_types, stream)
  urls = [sitemap_url("#{SITE_BASE_URL}/", entries.first && post_time(entries.first).iso8601)]

  entries.each do |entry|
    urls << sitemap_url("#{SITE_BASE_URL}#{post_path(entry)}", post_time(entry).iso8601)
  end

  # max_by post_time, not max_by the stored STRING. The comment on the post
  # sort spells out why a lexical compare is wrong here: a post written
  # "2026-08-22 10:00" sorts above one written "2026-08-22T09:00+02:00"
  # because a space is below a T, and an offset moves an instant without
  # moving its text. Three lastmods were picked that way -- so a crawler
  # could be told a listing was last touched by the wrong post.
  tags_map.each do |slug, data|
    latest = data[:posts].max_by { |p| post_time(p) }
    urls << sitemap_url("#{SITE_BASE_URL}/tag/#{slug}/", latest && post_time(latest).iso8601)
  end

  content_types.each do |type|
    # From the stream, not from the combined list: /type/<t>/ shows posts
    # and never pages, so a page could hand the listing a lastmod for
    # something that listing does not contain. The archive block below was
    # given `stream` for exactly this reason, and says so.
    type_posts = stream.select { |entry| dominant_content_type(entry) == type }
    latest = type_posts.max_by { |p| post_time(p) }
    urls << sitemap_url("#{SITE_BASE_URL}/type/#{type}/", latest && post_time(latest).iso8601)
  end

  # Every series listing, for the same reason as a tag's: the build writes
  # it, every post in the series links to it, and the sitemap was the one
  # place that had never heard of it.
  SERIES_MAP.each do |slug, in_series|
    next unless Slug.pageable?(slug)

    latest = in_series.max_by { |p| post_time(p) }
    urls << sitemap_url("#{SITE_BASE_URL}/series/#{slug}/", latest && post_time(latest).iso8601)
  end

  # The tag index: one entry, and only when there is at least one tag with a
  # page of its own -- a site with no tags builds no index and must not be
  # advertising one.
  urls << sitemap_url("#{SITE_BASE_URL}/tag/", entries.first && post_time(entries.first).iso8601) if tags_map.any?

  # The archive index and one entry per year that has posts in it, from the
  # stream and only the stream -- the same list the map itself is grouped
  # from. Grouping the combined list sent crawlers to /archive/<year>/ for
  # every year that held nothing but a page: an About page older than the
  # oldest post, or a Contact page added to a blog whose last post was two
  # years ago. The root was worse -- written unconditionally, while the build
  # skips the whole map when the stream is empty.
  unless stream.empty?
    urls << sitemap_url("#{SITE_BASE_URL}/archive/", stream.first && post_time(stream.first).iso8601)
    stream.group_by { |post| post_time(post).year }.each do |year, in_year|
      latest = in_year.max_by { |p| post_time(p) }
      urls << sitemap_url("#{SITE_BASE_URL}/archive/#{year}/", latest && post_time(latest).iso8601)
    end
  end

  <<~XML
    <?xml version="1.0" encoding="UTF-8"?>
    <urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
      #{urls.join("\n  ")}
    </urlset>
  XML
end

# Pages are sliced starting from the OLDEST post, so a page's contents never
# change once written. Slicing from the newest end (the obvious way) shifts
# every page boundary each time a post is added, which rewrites the whole
# archive on every new post -- expensive under a content-hash-based deploy.
#
# Numbers therefore run oldest-first: page 1 is the oldest posts, the highest
# number is the newest page and lives at base_path itself (/ or /tag/foo/)
# rather than under /page/. That newest page holds PAGE_SIZE..2*PAGE_SIZE-1
# posts and only splits off a fixed page once it reaches 2*PAGE_SIZE, so the
# landing page is never left nearly empty right after a split.
#
# Returns [[number, posts], ...] newest first, plus the count of fixed
# (already-final) pages.
# `oldest_first:` is for the one listing that is not a timeline. A series
# reads from part one -- tests/test_post_page.rb has held that since it was
# written -- and the anchoring below assumes the opposite: it takes the
# flexible landing page off the FRONT and slices the fixed /page/N/ pages
# off the TAIL, which is what makes "a page's contents never change once
# written" true when new posts arrive at the front.
#
# Handed an oldest-first list it did the reverse of what it promises: the
# fixed pages were cut from the NEWEST end, so every part added re-cut
# every one of them, and "Older ->" led towards the newest.
#
# Mirrored rather than reversed. Reversing the list would have fixed the
# paging by breaking the reading order; anchoring the fixed pages at the
# FRONT -- where the parts that will never change again are -- keeps both,
# and needs no new numbering and no new labels: page 1 is still the far
# end of the walk and the landing page is still the flexible one.
def anchored_pages(posts, oldest_first: false)
  fixed = posts.length < 2 * PAGE_SIZE ? 0 : (posts.length / PAGE_SIZE) - 1
  flexible_length = posts.length - fixed * PAGE_SIZE
  return [[[fixed + 1, posts]], fixed] if fixed.zero?

  if oldest_first
    pages = posts.first(fixed * PAGE_SIZE).each_slice(PAGE_SIZE).with_index.map do |slice, i|
      [i + 1, slice]
    end
    pages << [fixed + 1, posts.last(flexible_length)]
    return [pages, fixed]
  end

  pages = [[fixed + 1, posts.first(flexible_length)]]
  posts.drop(flexible_length).each_slice(PAGE_SIZE).with_index do |slice, i|
    pages << [fixed - i, slice]
  end
  [pages, fixed]
end

def page_url(number, fixed, base_path)
  return base_path.empty? ? '/' : "#{base_path}/" if number > fixed

  "#{base_path}/page/#{number}/"
end

# No "x / total" counter: the total changes whenever a new page is created,
# which would put a differing byte on every single page again -- the very
# churn the oldest-anchored slicing above exists to avoid.
def pagination_html(number, fixed, base_path = '')
  return '' if fixed.zero?

  newer = number <= fixed ? %(<a href="#{page_url(number + 1, fixed, base_path)}">#{h(t('pagination.newer'))}</a>) : ''
  older = number > 1 ? %(<a href="#{page_url(number - 1, fixed, base_path)}">#{h(t('pagination.older'))}</a>) : ''
  label = number > fixed ? t('pagination.latest') : t('pagination.page', number: number)
  %(<nav class="pagination" aria-label="#{h(t('pagination.nav_label'))}">#{newer}<span>#{h(label)}</span>#{older}</nav>)
end

# Templates only contain their own <main>; the header, nav, sidebar and
# footer live once in templates/layout.html.erb and templates/partials/.
# They used to be copy-pasted across all three templates, so every footer
# edit meant three edits that risked drifting apart.
LAYOUT = ERB.new(File.read(File.join(ROOT, 'templates', 'layout.html.erb'), encoding: 'utf-8'))
PARTIALS = {}
PARTIAL_RESULTS = {}

# Cached by name and local variables: partials don't depend on page content
# (nav, sidebar, footer are the same everywhere), so there are only ever a
# few distinct results. Without this cache, every single page would
# re-evaluate several ERB templates, roughly doubling build time on a large
# site.
def partial(name, **locals)
  PARTIAL_RESULTS[[name, locals]] ||= begin
    template = PARTIALS[name] ||=
      ERB.new(File.read(File.join(ROOT, 'templates', 'partials', "#{name}.html.erb"), encoding: 'utf-8'))
    template.result_with_hash(locals)
  end
end

# Which nav item the page being rendered belongs under, as the item's own
# href ('/' or '/type/<type>/') so the partial can compare without knowing
# anything about paths. Derived from the path layout() already receives, so
# no call site has to say where it is.
#
# Only listing pages get an active item. A post page deliberately doesn't
# light up its own type: the nav is a filter over the listings, and
# highlighting VIDEO on a video post would claim you're in the video
# listing when you aren't. Tag pages and the search page have no item to
# point at at all.
def nav_active_for(path)
  return '/' if path == '/' || path.start_with?('/page/')

  # Pagination lives under the type ('/type/video/page/2/'), so the item is
  # the first two segments rather than the whole path.
  type = path[%r{\A/type/([^/]+)/}, 1]
  return "/type/#{type}/" if type

  # A tag listing (and its pagination) belongs under the tag's own item,
  # for the menus that are made of tags rather than types; anything else --
  # a post, a generated page -- lights up only when an item points straight
  # at it. Both are matched against the menu the site actually has rather
  # than returned unconditionally, because the answer becomes a
  # PARTIAL_RESULTS key: returning every path would give each of thousands
  # of tag and post pages its own cache entry for an identical menu.
  tag = path[%r{\A/tag/([^/]+)/}, 1]
  candidate = tag ? "/tag/#{tag}/" : path
  NAV_ITEM_HREFS.include?(candidate) ? candidate : nil
end

# The entire attribute, or an empty string -- see the comment in
# templates/partials/nav.html.erb for why this isn't an <% if %> block.
def nav_current(href, active)
  href == active ? ' aria-current="page"' : ''
end

# The origins a set of posts needs for their comment threads: the instance
# each post was announced on (its own stored URL), plus the public Bluesky
# AppView for any post with a Bluesky record. Same shape as
# Embed.frame_origins_for -- a property of the posts on the page, not of
# the engine's current configuration.
def comment_origins_for(posts)
  # Moderated comments come from this origin whatever instance a post was
  # announced on, so the per-post grant that exists to survive a network
  # switch has nothing left to allow.
  return [] unless COMMENTS_APPROVAL.nil?

  Array(posts).filter_map do |post|
    next unless post.is_a?(Hash)

    if post['mastodon_url']
      uri = begin
        URI.parse(post['mastodon_url'])
      rescue StandardError
        nil
      end
      # The port is part of the origin: an instance on a non-default port
      # would otherwise be granted an origin the browser never matches, so
      # the very policy meant to allow its thread refuses it.
      next unless uri&.host

      origin = "#{uri.scheme}://#{uri.host}#{":#{uri.port}" if uri.port && uri.port != uri.default_port}"
      # A stored host is data, and this string ends up inside a policy
      # whose directives are separated by ";" and whose value sits in an
      # HTML attribute. Anything outside the shape of an origin is dropped
      # rather than escaped -- a host that needs escaping here is not a
      # host worth trusting with a connect-src grant.
      origin if origin.match?(%r{\Ahttps?://[A-Za-z0-9.-]+(?::\d+)?\z})
    elsif post['bluesky_uri']
      'https://public.api.bsky.app'
    end
  end.uniq
end

# `body_class` is how a stylesheet tells one listing page from another. CSS
# cannot read an address, so the first page of a listing and its /page/N/
# continuations were indistinguishable: a skin that wanted a lead card, or a
# profile block, on the first page only had nothing to hang the rule on, and
# both skins written against this engine hit it independently. The class is
# emitted on both sides -- page-first and page-cont -- rather than marking
# only the continuations, so a skin can scope its additions positively
# instead of writing them unconditionally and then undoing each property
# again further down.
def layout(main_html, title:, description:, path:, image: DEFAULT_OG_IMAGE, og_type: 'website',
           extra_head: '', frame_origins: [], comment_origins: [], body_class: nil)
  LAYOUT.result_with_hash(
    # Pre-rendered as the whole attribute, so a page without one keeps a bare
    # <body> rather than an empty class="" on every page of every site.
    body_attr: body_class ? %( class="#{body_class}") : '',
    main_html: main_html,
    page_title: title,
    page_description: description,
    page_url: "#{SITE_BASE_URL}#{path}",
    nav_active: nav_active_for(path),
    og_image: image,
    og_type: og_type,
    extra_head: extra_head,
    # The players a page carries decide its frame-src, so the policy is
    # computed here rather than widened for the whole site (csp_content).
    page_frame_origins: frame_origins,
    page_comment_origins: comment_origins
  )
end

# One compiled ERB per template, reused for every page it renders (recompiling
# the same source for every one of what can be thousands of listing pages is
# pure waste).
# A listing's own heading: what kind of listing it is, then what it is a
# listing OF. The kind stays in the markup and is hidden visually rather
# than dropped, because the alternative loses it entirely -- a screen
# reader on a tag page would announce "Bitwarden" and nothing else, and a
# pill's background colour is not read aloud. Which listings show the kind
# at all is a CSS decision (see .listing-heading__kind in site.css), so a
# site can put the word back with one rule.
#
# Only listings whose value is an arbitrary string get a kind: a tag name
# and a search query can be anything, so "Bitwarden" alone reads like a
# post title, while the eight content-type labels are a closed set that
# cannot be mistaken for one. That is why type listings pass no kind and
# always did without one.
# `value_href:` makes the heading itself the way back: a tag listing links
# to the index of tags, a year to the map of years. The same address the
# "back" link at the foot carries -- a reader who has scrolled to the top
# of a long year should not have to scroll to the bottom to leave it.
def listing_heading_html(value, kind: nil, variant: nil, value_id: nil, icon: nil, value_href: nil)
  value = value.to_s
  kind = kind.to_s
  return '' if value.empty? && kind.empty?

  classes = ['listing-heading']
  classes << "listing-heading--#{variant}" if variant
  parts = []
  parts << %(<span class="listing-heading__kind">#{h(kind)}</span>) unless kind.empty?
  parts << LISTING_HEADING_ICONS[icon] if icon && LISTING_HEADING_ICONS.key?(icon)
  id_attr = value_id ? %( id="#{h(value_id)}") : ''
  inner = value_href ? %(<a class="listing-heading__link" href="#{h(value_href)}">#{h(value)}</a>) : h(value)
  parts << %(<span class="listing-heading__value"#{id_attr}>#{inner}</span>)
  # h1, not h2. This is what the page is about -- the tag being listed, the
  # search being run -- and the posts under it are h2 already, so at h2 it
  # was a sibling of the things it introduces rather than their heading. A
  # listing had no h1 at all, which left every page in the archive except a
  # post and the cheat sheet with an outline that started at level two.
  %(<h1 class="#{classes.join(' ')}">#{parts.join}</h1>)
end

# The landing page is the one listing with nothing to announce: it is the
# site itself, and the banner has said so already. Giving it a visible
# heading would put a word on every front page built with this engine that
# nobody asked for -- so it gets the site's own title, clipped out of sight
