# The exact text content of the one inline <script> this site ever emits
# (see templates/layout.html.erb) -- computed once so its CSP hash (below)
# and the actual tag are guaranteed byte-identical. Keeping script-src free
# of 'unsafe-inline' means an actual XSS payload still can't run merely by
# getting itself onto the page; only this specific, build-generated script
# is allowlisted, by content hash rather than by trusting its origin.
CLIENT_I18N_SCRIPT = "window.BLOG_I18N = #{client_i18n_json};"
CLIENT_I18N_SCRIPT_HASH = "'sha256-#{Digest::SHA256.base64digest(CLIENT_I18N_SCRIPT)}'"

# Only adds the analytics/Mastodon origins to script-src/connect-src when
# those integrations are actually configured -- a site with neither gets a
# tighter policy for free, instead of a hardcoded allowlist for services it
# doesn't use.
def csp_content
  analytics_origin = ANALYTICS && ANALYTICS['src'] ? URI.parse(ANALYTICS['src']) : nil
  analytics_origin &&= "#{analytics_origin.scheme}://#{analytics_origin.host}"
  mastodon_origin = MASTODON_INSTANCE ? "https://#{MASTODON_INSTANCE}" : nil
  # Bluesky threads are read from the public AppView, no auth involved.
  bluesky_origin = COMMENT_NETWORK == :bluesky ? 'https://public.api.bsky.app' : nil

  script_src = ["'self'", CLIENT_I18N_SCRIPT_HASH, analytics_origin].compact.join(' ')
  connect_src = ["'self'", analytics_origin, mastodon_origin, bluesky_origin].compact.join(' ')

  "default-src 'self'; script-src #{script_src}; style-src 'self' 'unsafe-inline'; " \
    "img-src 'self' https: data:; font-src 'self'; connect-src #{connect_src}; " \
    "frame-src https://www.youtube.com https://www.youtube-nocookie.com; " \
    "object-src 'none'; base-uri 'self'; form-action 'self'"
end

