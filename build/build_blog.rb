# The crawlers that collect text to train on, as of this release. A list in
# the engine goes stale, which is why the free-text key below exists beside
# it -- but a list nobody has to research is the difference between a site
# that makes this choice and one that meant to.
#
# Off by default. Wanting to be findable in an answer somebody gets from a
# machine is a legitimate position, and it is not the engine's to take on
# a site's behalf.
#
# And it is a request, not a fence: some of these honour robots.txt and
# some do not. Anything here that said "blocks" would be a lie -- see
# docs/decisions.md.
AI_CRAWLERS = %w[GPTBot ChatGPT-User OAI-SearchBot ClaudeBot Claude-Web anthropic-ai
                 CCBot Google-Extended PerplexityBot Bytespider Amazonbot
                 Applebot-Extended meta-externalagent Diffbot Omgilibot].freeze

def robots_txt
  lines = ['User-agent: *', 'Allow: /']
  if SiteConfig.get('seo', 'block_ai_crawlers', default: false)
    AI_CRAWLERS.each { |agent| lines << '' << "User-agent: #{agent}" << 'Disallow: /' }
  end
  extra = SiteConfig.get('seo', 'robots_extra').to_s.strip
  lines << '' << extra unless extra.empty?
  # The blank line only when something was actually put between: a site
  # that configures neither has to get back the exact three lines it got
  # before this existed, or every install re-uploads a robots.txt to say
  # what it already said.
  lines << '' if lines.size > 2
  lines << "Sitemap: #{SITE_BASE_URL}/sitemap.xml"
  "#{lines.join("\n")}\n"
end

emit(File.join(PUBLIC_DIR, 'robots.txt'), robots_txt)

# An imported post keeps answering at the addresses its previous platform
# gave it: redirect_from is a list of site-root paths ("/bitwarden/",
# "/2020/01/some-post/") an importer writes when the new site lives on the
# old site's domain. Same stub as former_slugs, different history: that
# list is machine-managed rename history inside THIS site, this one is
# where the post lived before it arrived -- the two never mix. The paths
# are arbitrary, so unlike the former_slugs loop this one runs after
# EVERYTHING real -- posts, listings, search, feeds, root files -- and a
# stub yields to whatever the build already produced, out loud.
# The list itself now lives in PostAddress, so the build, the checker and
# the repair pass cannot drift apart about it.
REDIRECT_FROM_RESERVED = PostAddress::REDIRECT_RESERVED
# Pages too, for the reason above -- and because a source like Substack
# serves its pages under /p/<slug>, so the old address is a real one the
# importer records and this loop is the only thing that answers it.
(posts + pages + unlisted_posts).each do |post|
  Array(post['redirect_from']).each do |origin|
    parts = origin.to_s.split('/').reject(&:empty?)
    case PostAddress.redirect_refusal(origin)
    when :unusable
      warn t('build.redirect_from_unusable', slug: post['slug'], entry: origin.inspect)
      next
    when :reserved
      warn t('build.redirect_from_reserved', slug: post['slug'], entry: origin.inspect, segment: parts.first)
      next
    end

    # "/2009/05/some-post.html" was a FILE on Blogger, TypePad and
    # LiveJournal, and a static host answers that request with the literal
    # path -- a some-post.html/index.html directory would depend on the
    # server's index fallback for a URL that never had a trailing slash.
    # Anything else gets the directory-with-index shape former_slugs uses.
    dest = if parts.last.match?(/\.html?\z/i)
             File.join(PUBLIC_DIR, *parts)
           else
             File.join(PUBLIC_DIR, *parts, 'index.html')
           end

    # Two lookups, two different collisions: the destination itself, and a
    # ROOT FILE sitting where the path needs a directory (a stub at
    # "/rss.xml/whatever/" would need rss.xml to be one). Both end in the
    # same loud skip -- the build's own output always wins over a stub.
    prefix_file = (0...parts.size).map { |i| File.join(PUBLIC_DIR, *parts[0..i]) }.find { |p| written_already?(p) }
    if written_already?(dest) || prefix_file
      warn t('build.redirect_from_taken', slug: post['slug'], origin: origin)
      next
    end
    # The third collision: the destination is a DIRECTORY an earlier stub
    # created (entries "/x.html/sub/" and "/x.html", in that order --
    # WRITTEN knows the file inside, not the directory itself). Writing a
    # file over a directory is EISDIR, and one bad pair of imported
    # entries must not kill the whole build.
    if File.directory?(dest)
      warn t('build.redirect_from_directory', slug: post['slug'], origin: origin)
      next
    end

    emit(dest, redirect_stub_html(post))
  end
end

# Prune walks all 16,000 entries of a large public.nosync/ looking for what
# the build no longer produces -- a second of every publish, and on an
# ordinary publish it finds nothing, because an ordinary publish adds pages
# and drops none.
#
# So it is asked first whether anything COULD have been orphaned: is every
# public.nosync/ is swept on every build, and the cache does not get a say.
#
# It used to: when no file the last build wrote had stopped being written,
# the walk was skipped. That reasoning was sound about outputs and blind to
# everything else, because a record can only miss what it once held. Three
# things arrive in public.nosync/ without ever being in it -- the palette
# preview the style wizard leaves behind (and promises the next build will
# take down), whatever a build that died halfway had already written, and
# anything a person or a script put there -- and all three then survived
# every later build, and every deploy mirrored them onto the live site.
#
# The sweep costs 1.2 s on a 4,394-post archive, against 10.3 s that the
# same publish cost before the cache existed. Correctness at a third of
# what was saved is a trade worth making, and "the site holds exactly what
# the archive says" is not a promise to make conditionally.
removed = prune_public

# Written here and nowhere else: at the end, on the way out of a build that
# reached the end. An at_exit hook would save this state after a build that
# died halfway through writing the site, and the next build would then skip
# the half that never got written -- a site permanently missing pages, with
# nothing saying so.
