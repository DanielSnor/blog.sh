tags_map = {}
overlong_tags = []
posts.each do |post|
  # Folded by SLUG before anything is appended, because the map groups by
  # slug while the loop walked tag STRINGS: "sci-fi" and "Sci Fi", "Praha"
  # and "praha", "Cesko" and "Česko" -- or the same tag simply typed twice
