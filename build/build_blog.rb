  # nobody wins; the shape is settled at the door instead. check refuses
  # such a post separately, so this is the second line of defence rather
  # than a licence to write one.
  parsed['content'] = parsed['content'].is_a?(Array) ? parsed['content'].select { |b| b.is_a?(Hash) } : []
  # And `title`, for the same reason and at the same door. The engine's
  # contract for an untitled post is `title: nil` -- then the date becomes
  # the heading, <title> falls back to the post's first sentence, and a
  # listing link carries that sentence as its text. An empty STRING is
  # what the feed, WordPress and Squarespace importers write for an item
  # with no title, and it is truthy: the page shipped a blank <title>, an
  # empty <h1> and archive links with nothing to click.
  parsed['title'] = nil if parsed['title'].to_s.strip.empty?
  parsed['__year'] = File.basename(File.dirname(f))
  # The file this came out of. The duplicate message below names it,
  # because an address does not find a file: two pages collide on a slug
  # however far apart their dates are, and "/about/ (2x)" leaves the reader
  # grepping the archive for the pair they have to choose between.
  parsed['__path'] = f
  parsed
rescue JSON::ParserError, SystemCallError => e
  unreadable << "  #{f}: #{e.message.lines.first.to_s.strip[0, 100]}"
  nil
end
unless unreadable.empty?
  abort("#{t('build.unreadable_posts')}\n#{unreadable.join("\n")}")
end

# Two posts sharing a year and slug would point at the same output path
# (post_path, output_dir) and the same media/<year>/<slug>/ -- one would
# silently disappear, overwritten by the other, and their media would get
# mixed up. This used to be a silent risk on any conflicting file copy
# (cloud sync, a manual cp/SFTP on the server) -- better to fail loudly here
# than publish a broken archive.
# Asked of PostAddress, not worked out here, because the checker and the
# rename guard have to refuse exactly what this refuses -- and when the
# three of them each had their own version, a rename could hand the archive
# a state this abort then stopped the whole site on. The second key is new
# here: two PAGES of one slug are served at one address however far apart
# their dates are, and this used to build both and keep whichever it wrote
# last, silently.
collisions = {}
posts.each do |p|
  PostAddress.collision_keys(p, year: post_time(p).year).each { |key| (collisions[key] ||= []) << p }
end
duplicates = collisions.select { |_, v| v.size > 1 }

def collision_lines(group)
  group.map { |(year, slug), dupes|
    where = dupes.map { |p| "      #{p['__path']}" }.join("\n")
    "  #{year == 'page' ? "/#{slug}/" : "#{year}/#{slug}"} (#{dupes.size}x)\n#{where}"
  }.join("\n")
end

# Two posts sharing a year and a slug cannot both be written: one output
# directory, one media/<year>/<slug>/ between them, so one would silently
# disappear. That has stopped the build since long before this rule was
# written down in one place, and it still does.
same_file, at_the_root = duplicates.partition { |(year, _), _| year != 'page' }
unless same_file.empty?
  abort("#{t('build.duplicate_address')}\n#{collision_lines(same_file)}")
end

# Two PAGES at one address lose one of the two as well -- but this one
# warns rather than stops, and the difference is deliberate. Refusing to
# build was tried and turned every path that writes a post into a way to
# take the site down, the scheduler's cron included, where nobody is at
# the keyboard to read the error and the archive stays broken until
# somebody notices the site has stopped updating. `check` calls this an
# error and the guards refuse to create it; a site that already has one
# keeps being served, one page short and saying so on every build.
at_the_root.each do |(_, slug), dupes|
  # Which one survives is worth saying out loud: posts are written newest
  # first, so the page that stays is the OLDER of the two -- the opposite
  # of what somebody who just wrote the second one expects. And the loser
  # does not disappear quietly: it keeps its entry in the sitemap and in
  # the search index, both of which then point a reader at the winner's
  # text under the loser's title.
  warn("#{t('build.two_pages', count: dupes.size, slug: slug)}\n" \
       "#{dupes.map { |p| "      #{p['__path']}" }.join("\n")}\n" \
       "#{t('build.two_pages_fix')}")
end

# Slug is a tiebreaker, not decoration: sort_by isn't stable, and posts
# imported from some other platform/era can share an exact timestamp with
# another post. Without a tiebreaker their relative order shifts between
# builds, which silently changes the contents of dozens of pages and forces
# a content-hash-based deploy to re-upload them even though nothing was edited.
# By the INSTANT, not by the stored string. A lexical compare puts a post
# stored as 2026-06-08T06:00:00Z after one stored as
# 2026-06-08T07:00:00+02:00, though the second happened first -- and an
# archive that mixes offsets is every archive that was imported, since
# the importers store UTC and the CLI writes the site's own offset.
posts.sort_by! { |p| [post_time(p), p['slug']] }
posts.reverse!

# From here on, `posts` means only published posts -- listings, tags, types,
# RSS, the sitemap and the search index all draw from it unchanged. Drafts
# only get their own page at a hidden address.
drafts, posts = posts.partition { |p| draft?(p) }
# Pages come out of `posts` here, once, so that everything downstream --
# listings, tags, types, RSS, pagination -- keeps drawing from a list that
# means "the stream" and needs no exception of its own. The two consumers
# that DO want them (the sitemap and the search index) ask for them by
# name, which is the right way round: being findable is the point of a
# page, and being in the stream is not.
#
# A page at the root cannot be allowed to shadow an address the engine
# already owns. The rest of the site lives under /posts/, /tag/, /type/,
# /draft/ and the two generated pages, so those are the names to refuse.
# `archive` joined this list late, and the gap had a cost: the map was
# added in 1.5 without touching these names, so a page slugged `archive`
# was accepted, rendered, and then flatly overwritten by the map -- with
# no warning from the build, a green `check`, a silent `doctor`, and the
# page still listed in the search index, so searching for it by name
# handed the reader the map. `archive` is one of the commonest names a
# blog has for a page.
RESERVED_ROOT_SEGMENTS = %w[posts tag type draft search markdown archive assets page rss.xml
                            sitemap.xml robots.txt 404 favicon.ico].freeze
pages, posts = posts.partition { |p| page?(p) }
# Out of the stream on the same principle as pages, one step further:
# a page is taken out of the listings but stays findable (sitemap,
# search), while an unlisted post is out of those too. So it is
# partitioned here and then added back BY NAME to the two things it is
# still entitled to -- its own page, and the redirect stubs for
# addresses it used to have.
unlisted_posts, posts = posts.partition { |p| unlisted?(p) }
pages.reject! do |page|
  next false unless RESERVED_ROOT_SEGMENTS.include?(page['slug'].to_s.downcase)

  warn t('build.page_reserved_name', slug: page['slug'])
  true
end
# `unlisted` on a PAGE means the same as it does on a post, and pages are
# the likeliest thing to be marked with it: a migration leaves behind a
# "Sample Page" and a "Privacy Policy" nobody wrote, and unlisted is what
# somebody reaches for instead of deleting them. Taken out of `pages`
# here, they join the same list, so the sitemap and the search index --
# the only two things `pages` still feeds -- stop contradicting the
# noindex the page's own <head> already carried.
#
# After the reserved-name refusal above, not before it: a page called
# "posts" must be refused whether or not it is also unlisted.
unlisted_pages, pages = pages.partition { |p| unlisted?(p) }
unlisted_posts.concat(unlisted_pages)
# A draft without its token would build at the GUESSABLE /draft//slug/ --
# every writer in the engine guarantees the token, so a missing one means
# a hand-copied or hand-edited JSON, and the unguessable-URL design must
# not quietly fail for it. Skipped and named, not built.
drafts.reject! do |post|
  next false unless post['draft_token'].to_s.strip.empty?

  warn t('build.draft_no_token', slug: post['slug'])
  true
end

